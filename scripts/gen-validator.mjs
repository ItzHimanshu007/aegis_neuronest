#!/usr/bin/env node
/**
 * Precompiles shared/schema/*.v2.schema.json into browser-safe standalone
 * JavaScript validators at BUILD time.
 *
 * AJV standalone can emit a runtime `require()` for helpers such as
 * ajv/dist/runtime/ucs2length even when `code.esm` is enabled.
 *
 * We therefore:
 *   1. Generate the validator with AJV standalone.
 *   2. Bundle that generated module with esbuild.
 *
 * The final artifact is a self-contained ESM module with no runtime AJV
 * dependency and no require()/eval/new Function in the extension.
 */
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outDir = path.join(rootDir, 'extension', 'privacy', 'generated');
const tempDir = path.join(outDir, '.tmp');

await mkdir(outDir, { recursive: true });
await mkdir(tempDir, { recursive: true });

for (const name of ['payload', 'plan']) {
  const schemaPath = path.join(
    rootDir,
    'shared',
    'schema',
    `${name}.v2.schema.json`,
  );

  const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

  const ajv = new Ajv2020({
    strict: true,
    strictRequired: false,
    allErrors: true,
    code: {
      source: true,
      esm: true,
    },
  });

  const validate = ajv.compile(schema);

  const generatedSource =
    `// GENERATED by pnpm gen:validator; do not edit.\n` +
    `/* eslint-disable */\n` +
    standaloneCode(ajv, validate);

  const tempInput = path.join(tempDir, `${name}Validator.input.js`);
  const outputFile = path.join(outDir, `${name}Validator.js`);

  await writeFile(tempInput, generatedSource);

  await build({
    entryPoints: [tempInput],
    outfile: outputFile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: false,
    sourcemap: false,
    logLevel: 'silent',
  });

  const dts = `// GENERATED by pnpm gen:validator; do not edit.
export interface ValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}

declare const validate: {
  (data: unknown): boolean;
  errors?: ValidationError[] | null;
};

export default validate;
`;

  await writeFile(
    path.join(outDir, `${name}Validator.d.ts`),
    dts,
  );

  console.log(`wrote ${name}Validator.js`);
}

console.log('validators bundled with esbuild');