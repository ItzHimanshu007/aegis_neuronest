#!/usr/bin/env node
/**
 * Precompiles shared/schema/payload.v1.schema.json into a standalone JavaScript validator at
 * BUILD time, written to extension/privacy/generated/payloadValidator.js.
 *
 * WHY THIS EXISTS: ajv's normal `ajv.compile(schema)` builds the validator by generating source
 * and evaluating it with `new Function`. Inside a browser extension that is blocked twice over:
 *
 *   1. The extension CSP (`script-src 'self'`, no `unsafe-eval`) refuses it at runtime — the real
 *      failure was "Evaluating a string as JavaScript violates the following Content Security
 *      Policy directive".
 *   2. AGENTS.md invariant 7 forbids `eval`/`new Function` outright, independently of CSP.
 *
 * Standalone mode does the codegen here, in Node, and emits a plain module. The extension imports
 * a normal function — no eval, no CSP violation, and ajv itself no longer ships in the bundle.
 *
 * Run via `pnpm gen:validator`. extension/privacy/__tests__/payloadValidator.test.ts proves the
 * generated validator agrees with the schema on the shared fixtures.
 */
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const schemaPath = path.join(rootDir, 'shared', 'schema', 'payload.v1.schema.json');
const outDir = path.join(rootDir, 'extension', 'privacy', 'generated');
const outPath = path.join(outDir, 'payloadValidator.js');
const dtsPath = path.join(outDir, 'payloadValidator.d.ts');

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

// `strictRequired: false` for the same reason scripts/validate-fixtures.mjs sets it — the
// conditional `allOf` blocks add `required` without redeclaring the property's type.
const ajv = new Ajv2020({ strict: true, strictRequired: false, allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);

const banner = `// GENERATED by \`pnpm gen:validator\` from shared/schema/payload.v1.schema.json.
// Do not hand-edit. See scripts/gen-validator.mjs for why this is precompiled rather than
// compiled at runtime (extension CSP + AGENTS.md invariant 7: no eval, no new Function).
/* eslint-disable */
`;

await mkdir(outDir, { recursive: true });
await writeFile(outPath, banner + standaloneCode(ajv, validate), 'utf8');

await writeFile(
  dtsPath,
  `// GENERATED by \`pnpm gen:validator\`. Do not hand-edit.
export interface ValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}

declare const validate: {
  (data: unknown): boolean;
  errors?: ValidationError[] | null;
};

export default validate;
`,
  'utf8',
);

console.log(`wrote ${path.relative(rootDir, outPath)}`);
