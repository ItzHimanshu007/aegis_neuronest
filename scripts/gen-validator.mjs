#!/usr/bin/env node
/**
 * Precompiles shared/schema/*.v2.schema.json into browser-safe standalone
 * JavaScript validators at BUILD time.
 *
 * AJV standalone can emit a runtime `require()` for helpers such as
 * ajv/dist/runtime/ucs2length even when `code.esm` is enabled.
 *
 * We therefore:
 *   1. Generate the validator with AJV standalone.
 *   2. Bundle that generated module with esbuild.
 *
 * The final artifact is a self-contained ESM module with no runtime AJV
 * dependency and no require()/eval/new Function in the extension.
 */
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outDir = path.join(rootDir, 'extension', 'privacy', 'generated');

await mkdir(outDir, { recursive: true });

for (const name of ['payload', 'plan']) {
  const schemaPath = path.join(
    rootDir,
    'shared',
    'schema',
    `${name}.v2.schema.json`,
  );

  const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

  const ajv = new Ajv2020({
    strict: true,
    strictRequired: false,
    allErrors: true,
    code: {
      source: true,
      esm: true,
    },
  });

  const validate = ajv.compile(schema);

  // AJV standalone's own codegen reuses local var names (e.g. `_valid0`) across nested if/then
  // blocks within one compiled function — harmless at runtime (`var` hoists to the function and
  // both declarations just reassign it), but flagged by `no-redeclare` under static analysis.
  //
  // A leading `/* eslint-disable */` comment used to suppress this before esbuild bundling was
  // introduced. esbuild's printer does not preserve an ordinary (non-"legal") comment once it
  // restructures the module to wrap the AJV runtime helper's `require()` call (the exact thing
  // this bundling step exists to eliminate) in its own shim — the comment is silently dropped from
  // the bundled output, which is what broke lint. Marking it a "legal" comment (`/*!`) survives
  // esbuild's printer, but ESLint's own directive-comment parser only recognizes a comment whose
  // trimmed text starts with `eslint-disable` — the leading `!` disqualifies it there too, so no
  // single comment satisfies both tools at once.
  //
  // Fix: don't ask esbuild's printer to carry the directive at all. Build with `write: false`,
  // then prepend the header/disable comment ourselves, in this script, as a plain string
  // concatenation onto esbuild's already-finished output — no printer involved for this part, so
  // nothing can drop it. This is generation, not hand-editing: the same automated step that already
  // writes the "GENERATED" header now writes the eslint-disable line right beside it.
  const generatedSource = standaloneCode(ajv, validate);
  const outputFile = path.join(outDir, `${name}Validator.js`);

  // Fed to esbuild via `stdin` rather than a temp file on disk: no intermediate file means nothing
  // for `eslint .` to pick up (the previous extension/privacy/generated/.tmp/*.input.js WAS being
  // linted directly — the raw pre-bundle AJV output still has a genuine `require()` call
  // (no-require-imports) and the same `_valid0`-reuse pattern as the final file, no disable comment
  // yet since that's only added below), and no leftover artifact to forget to clean up. `resolveDir`
  // tells esbuild to resolve bare imports (e.g. `require("ajv/dist/runtime/ucs2length")`) as if this
  // source lived at the repo root, so it still finds `node_modules/ajv` normally.
  const result = await build({
    stdin: {
      contents: generatedSource,
      resolveDir: rootDir,
      sourcefile: `${name}Validator.input.js`,
      loader: 'js',
    },
    write: false,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: false,
    sourcemap: false,
    logLevel: 'silent',
  });

  const header = `// GENERATED by pnpm gen:validator; do not edit.\n/* eslint-disable */\n`;
  await writeFile(outputFile, header + result.outputFiles[0].text);

  const dts = `// GENERATED by pnpm gen:validator; do not edit.
export interface ValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}

declare const validate: {
  (data: unknown): boolean;
  errors?: ValidationError[] | null;
};

export default validate;
`;

  await writeFile(
    path.join(outDir, `${name}Validator.d.ts`),
    dts,
  );

  console.log(`wrote ${name}Validator.js`);
}

console.log('validators bundled with esbuild');